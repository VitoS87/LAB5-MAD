fun main() {
    // Пример входного списка чисел (может содержать до 10000 элементов)
    val numbers: List<Int> = listOf(1, 2, 3, 2, 1, 4, 5, 4, 100, 5)

    // Преобразуем во множество (Set) для автоматического удаления дубликатов
    val uniqueNumbers: Set<Int> = numbers.toSet()

    // Выводим количество различных чисел
    println("Количество различных чисел: ${uniqueNumbers.size}")
}
